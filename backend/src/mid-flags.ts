const MMSI_MID_DIVISOR = 1_000_000;

/** Flag state for an MMSI, from its leading Maritime Identification Digits. */
export function flagFromMmsi(mmsi: number): string {
  const mid = Math.floor(mmsi / MMSI_MID_DIVISOR);
  return MID_COUNTRIES[mid] ?? 'Unknown';
}
